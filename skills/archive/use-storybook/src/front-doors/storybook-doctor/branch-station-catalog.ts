const contractEntries = Object.entries(storybookDoctorContracts) as Array<
	[
		StorybookDoctorCommand,
		(typeof storybookDoctorContracts)[StorybookDoctorCommand],
	]
>;

export function projectStorybookDoctorStationDiscovery() {
	return projectCommandDiscoveryTree(contractEntries);
}

export function findStorybookDoctorBranchStationCatalogDrift(
	evidence: readonly BranchStationEvidence[] = [],
) {
	return findBranchStationCatalogDrift({
		discovery: projectStorybookDoctorStationDiscovery(),
		catalog: storybookDoctorBranchStationCatalog,
		evidence,
		path: "skills/use-storybook/src/front-doors/storybook-doctor/branch-station-catalog.ts",
	});
}

export function projectStorybookDoctorStationMap(
	evidence: readonly BranchStationEvidence[] = [],
): StationMap {
	return projectStationMap({
		discovery: projectStorybookDoctorStationDiscovery(),
		catalog: storybookDoctorBranchStationCatalog,
		evidence,
		path: "skills/use-storybook/src/front-doors/storybook-doctor/branch-station-catalog.ts",
	});
}
